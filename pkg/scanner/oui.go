// LookupVendor returns the hardware manufacturer for a given MAC address.
func LookupVendor(mac string) string {
	clean := strings.ToUpper(strings.ReplaceAll(strings.ReplaceAll(mac, ":", ""), "-", ""))
	if len(clean) < 6 {
		return "Unknown"
	}
	prefix := clean[:6]

	if vendor, found := ouiTable[prefix]; found {
		return vendor
	}

	// Try 7-char or 9-char sub-blocks if needed, or fallback prefix
	shortPrefix := clean[:4]
	if vendor, found := shortOuiTable[shortPrefix]; found {
		return vendor
	}

	return "Unknown Manufacturer"
}

